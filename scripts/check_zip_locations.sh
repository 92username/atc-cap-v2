    if [ ! -z "$LATEST_ZIP" ]; then
        SIZE=$(du -h "$LATEST_ZIP" | cut -f1)
        FILE_COUNT=$(unzip -l "$LATEST_ZIP" 2>/dev/null | grep "Archive:" | grep -o '[0-9]* files' | grep -o '[0-9]*' || echo "0")
        echo "     $LATEST_ZIP ($SIZE, $FILE_COUNT arquivos)"
        if [ "$SIZE" = "22B" ] || [ "$SIZE" = "22" ]; then
            echo "     ⚠️ ZIP MUITO PEQUENO - Provavelmente vazio!"
        fi
    fi
fi
